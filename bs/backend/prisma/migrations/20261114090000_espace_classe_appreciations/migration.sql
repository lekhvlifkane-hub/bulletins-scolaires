-- Espace classe : règles d'appréciation configurables, enseignant par matière,
-- statut redoublant de l'inscription et indicateurs automatique/manuel.
CREATE TYPE "AppreciationRuleScope" AS ENUM ('MATIERE', 'MENTION', 'DECISION', 'GENERALE');

ALTER TABLE "AnnualSummary" ADD COLUMN     "appreciationAuto" BOOLEAN NOT NULL DEFAULT true,
ADD COLUMN     "decisionAuto" BOOLEAN NOT NULL DEFAULT true,
ADD COLUMN     "mentionAuto" BOOLEAN NOT NULL DEFAULT true;

ALTER TABLE "Appreciation" ADD COLUMN     "autoGenerated" BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE "ClassroomSubject" ADD COLUMN     "teacherName" TEXT;

ALTER TABLE "Enrollment" ADD COLUMN     "isRepeating" BOOLEAN NOT NULL DEFAULT false;

ALTER TABLE "ReportCard" ADD COLUMN     "appreciationAuto" BOOLEAN NOT NULL DEFAULT true,
ADD COLUMN     "decisionAuto" BOOLEAN NOT NULL DEFAULT true,
ADD COLUMN     "mentionAuto" BOOLEAN NOT NULL DEFAULT true;

UPDATE "ReportCard" SET "mentionAuto" = false WHERE "mention" IS NOT NULL;
UPDATE "ReportCard" SET "appreciationAuto" = false WHERE "appreciation" IS NOT NULL;
UPDATE "ReportCard" SET "decisionAuto" = false WHERE "decisionConseil" IS NOT NULL;

CREATE TABLE "AppreciationRule" (
    "id" TEXT NOT NULL,
    "schoolId" TEXT NOT NULL,
    "scope" "AppreciationRuleScope" NOT NULL,
    "code" TEXT NOT NULL,
    "label" TEXT NOT NULL,
    "minScore" DECIMAL(5,2),
    "maxScore" DECIMAL(5,2),
    "content" TEXT NOT NULL,
    "sortOrder" INTEGER NOT NULL DEFAULT 0,
    "isActive" BOOLEAN NOT NULL DEFAULT true,
    "deletedAt" TIMESTAMP(3),
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "AppreciationRule_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "AppreciationRule_schoolId_scope_isActive_idx" ON "AppreciationRule"("schoolId", "scope", "isActive");

CREATE UNIQUE INDEX "AppreciationRule_schoolId_scope_code_key" ON "AppreciationRule"("schoolId", "scope", "code");

ALTER TABLE "AppreciationRule" ADD CONSTRAINT "AppreciationRule_schoolId_fkey" FOREIGN KEY ("schoolId") REFERENCES "School"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

UPDATE "AnnualSummary" SET "mentionAuto" = false WHERE "mention" IS NOT NULL;
UPDATE "AnnualSummary" SET "appreciationAuto" = false WHERE "appreciation" IS NOT NULL;
UPDATE "AnnualSummary" SET "decisionAuto" = false WHERE "decisionConseil" IS NOT NULL;
